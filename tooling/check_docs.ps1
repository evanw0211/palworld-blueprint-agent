#!/usr/bin/env pwsh
# 文档契约门禁：校验 docs 的 kind、入口节、ToC 锚点、相对链接与生成说明。
# 契约 owner：docs/agent-notes/AN-0002-docs-contract.md
# 退出码：0 = 全部通过；1 = 有失败项（逐条打印 file:line — 原因）。
#
# 设计取舍：
# - 只检查文本结构，不判断内容真伪（内容是评审与实跑的职责）。
# - archive/research/、archive/ue4ss/ 是冻结记录集：按「归档后不得再编辑」豁免；
#   archive/README.md 是活页索引，照常检查。
# - 生成文件（data/catalog_summary.md）不套入口节，但必须带生成说明。

[CmdletBinding()]
param(
    [string]$Root = (Split-Path -Parent $PSScriptRoot)
)

$ErrorActionPreference = 'Stop'
$Root = (Resolve-Path -LiteralPath $Root).Path

$AllowedKinds = @(
    'overview', 'how-to', 'tutorial', 'component-reference', 'library-reference',
    'index', 'decision-record', 'reference', 'research'
)
$GeneratedMarkers = @('Generated by', '生成，勿手改', '勿手改')
$FrozenPrefixes = @('archive/research/', 'archive/ue4ss/')

$script:Failures = [System.Collections.Generic.List[object]]::new()
$script:CheckedPages = 0
$script:CheckedLinks = 0

function Add-Failure([string]$Rel, [int]$Line, [string]$Message) {
    $script:Failures.Add([pscustomobject]@{ File = $Rel; Line = $Line; Message = $Message })
}

function Get-Slug([string]$Text) {
    $t = $Text.Trim().ToLowerInvariant()
    $t = [regex]::Replace($t, '[^\p{L}\p{Nd}\s\-_]', '')
    $t = [regex]::Replace($t, '\s+', '-')
    return $t
}

# 返回 @{ Text=行, Number=行号 } 的数组，跳过围栏代码块。
function Get-ProseLines([string[]]$Lines) {
    $out = [System.Collections.Generic.List[object]]::new()
    $inFence = $false
    for ($i = 0; $i -lt $Lines.Length; $i++) {
        $line = $Lines[$i]
        if ($line -match '^\s*(```|~~~)') { $inFence = -not $inFence; continue }
        if ($inFence) { continue }
        $out.Add([pscustomobject]@{ Text = $line; Number = $i + 1 })
    }
    return $out
}

function Get-Headings([string[]]$Lines) {
    $map = @{}   # slug -> line number
    $list = [System.Collections.Generic.List[object]]::new()
    foreach ($item in (Get-ProseLines $Lines)) {
        if ($item.Text -match '^#{1,6}\s+(.+?)\s*#*\s*$') {
            $raw = $Matches[1].Trim()
            $slug = Get-Slug $raw
            $list.Add([pscustomobject]@{ Text = $raw; Slug = $slug; Number = $item.Number })
            if (-not $map.ContainsKey($slug)) { $map[$slug] = $item.Number }
        }
    }
    return @{ Map = $map; List = $list }
}

function Resolve-LinkTarget([string]$BaseDir, [string]$Target) {
    $path = $Target
    if ($path -match '^<(.+)>$') { $path = $Matches[1] }
    if ($path -match '\s') { $path = ($path -split '\s+')[0] }
    $path = $path.Replace('\', '/')
    try { $path = [uri]::UnescapeDataString($path) } catch { }
    return [IO.Path]::GetFullPath((Join-Path $BaseDir $path))
}

$files = Get-ChildItem -LiteralPath $Root -Recurse -File -Filter *.md |
    Where-Object {
        $_.FullName -notmatch '\\\.git\\|\\node_modules\\|\\meshes_new\\|\\out\\'
    } | Sort-Object FullName

foreach ($file in $files) {
    $rel = [IO.Path]::GetRelativePath($Root, $file.FullName).Replace('\', '/')
    $lines = Get-Content -LiteralPath $file.FullName -Encoding UTF8
    $text = ($lines -join "`n")
    $isFrozen = $false
    foreach ($p in $FrozenPrefixes) { if ($rel.StartsWith($p, [StringComparison]::OrdinalIgnoreCase)) { $isFrozen = $true } }
    $isGenerated = $file.Name -eq 'catalog_summary.md'
    foreach ($marker in $GeneratedMarkers) {
        if ($text -match [regex]::Escape($marker) -and $rel -like 'data/*') { $isGenerated = $true }
    }
    if ($isFrozen) { continue }

    if ($isGenerated) {
        $hasMarker = $false
        foreach ($marker in $GeneratedMarkers) { if ($text -match [regex]::Escape($marker)) { $hasMarker = $true } }
        if (-not $hasMarker) { Add-Failure $rel 1 '生成文件缺少「生成 / 勿手改」说明与生成器指向' }
        continue
    }

    $script:CheckedPages++

    # 1) frontmatter：description + kind
    $kind = $null
    if ($lines.Length -lt 3 -or $lines[0].Trim() -ne '---') {
        Add-Failure $rel 1 '缺少 frontmatter（首行应为 ---）'
    }
    else {
        $end = -1
        for ($i = 1; $i -lt [Math]::Min($lines.Length, 30); $i++) { if ($lines[$i].Trim() -eq '---') { $end = $i; break } }
        if ($end -lt 0) { Add-Failure $rel 1 'frontmatter 未闭合（30 行内找不到 ---）' }
        else {
            for ($i = 1; $i -lt $end; $i++) {
                if ($lines[$i] -match '^description:\s*(.+)$' -and $Matches[1].Trim().Trim('"').Trim("'").Length -eq 0) {
                    Add-Failure $rel ($i + 1) 'description 为空'
                }
                if ($lines[$i] -match '^kind:\s*(.+)$') { $kind = $Matches[1].Trim().Trim('"').Trim("'") }
            }
            if (-not $kind) { Add-Failure $rel 2 'frontmatter 缺少 kind' }
            elseif ($AllowedKinds -notcontains $kind) { Add-Failure $rel 2 "未知 kind: $kind" }
        }
    }

    $isDecision = ($kind -eq 'decision-record')

    # 2) 入口节：decision-record 反过来不写摘要/目录
    if ($isDecision) {
        if ($text -match '(?m)^## 摘要\s*$') { Add-Failure $rel 1 '决策笔记不应有 ## 摘要（AN 约定）' }
        if ($text -match '(?m)^## 目录\s*$') { Add-Failure $rel 1 '决策笔记不应有 ## 目录（AN 约定）' }
        if ($text -notmatch '\*\*状态：\*\*') { Add-Failure $rel 1 '决策笔记缺少状态行（**状态：**）' }
        if ($text -notmatch '\*\*日期：\*\*') { Add-Failure $rel 1 '决策笔记缺少日期行（**日期：**）' }
    }
    else {
        foreach ($section in @('## 摘要', '## 目录')) {
            if ($text -notmatch ('(?m)^' + [regex]::Escape($section) + '\s*$')) { Add-Failure $rel 1 "缺少入口节 $section" }
        }
        if ($text -notmatch '(?m)^-----+\s*$') { Add-Failure $rel 1 '缺少入口节分隔线 -----' }
    }
    if ($text -notmatch '(?m)^## Dev Note\s*$') { Add-Failure $rel 1 '缺少页尾 ## Dev Note' }

    # 3) ToC 锚点必须指到本页标题（只对非决策页）
    $headings = Get-Headings $lines
    if (-not $isDecision -and $text -match '(?m)^## 目录\s*$') {
        $inToc = $false
        foreach ($item in (Get-ProseLines $lines)) {
            $t = $item.Text
            if ($t -match '^## 目录\s*$') { $inToc = $true; continue }
            if ($inToc -and $t -match '^##\s') { break }
            if ($inToc -and $t -match '^\s*-\s+\[(.+?)\]\(#([^)]+)\)') {
                $anchor = $Matches[2]
                if (-not $headings.Map.ContainsKey($anchor)) {
                    Add-Failure $rel $item.Number "ToC 锚点 #$anchor 找不到对应标题"
                }
            }
        }
    }

    # 4) 相对链接必须存在；带 #fragment 的还要在目标页里找到锚点
    foreach ($item in (Get-ProseLines $lines)) {
        $t = $item.Text
        foreach ($m in [regex]::Matches($t, '(?<!!)\[([^\]\n]*)\]\(([^)\n]+)\)')) {
            $target = $m.Groups[2].Value.Trim()
            if ($target -match '^[a-zA-Z][a-zA-Z0-9+.-]*:') { continue }   # http(s)/mailto 等
            $script:CheckedLinks++
            $hash = ''
            $pathPart = $target
            $idx = $target.IndexOf('#')
            if ($idx -ge 0) { $pathPart = $target.Substring(0, $idx); $hash = $target.Substring($idx + 1) }
            if ($pathPart.Length -eq 0) {
                if ($hash -and -not $headings.Map.ContainsKey($hash)) {
                    Add-Failure $rel $item.Number "页内锚点 #$hash 找不到对应标题"
                }
                continue
            }
            $full = Resolve-LinkTarget $file.DirectoryName $pathPart
            if (-not (Test-Path -LiteralPath $full)) {
                Add-Failure $rel $item.Number "链接目标不存在: $pathPart"
                continue
            }
            if ($hash -and (Test-Path -LiteralPath $full -PathType Leaf)) {
                $targetLines = Get-Content -LiteralPath $full -Encoding UTF8
                $targetHeadings = Get-Headings $targetLines
                if (-not $targetHeadings.Map.ContainsKey($hash)) {
                    $targetRel = [IO.Path]::GetRelativePath($Root, $full).Replace('\', '/')
                    Add-Failure $rel $item.Number "跨页锚点 #$hash 在 $targetRel 中不存在"
                }
            }
        }
    }
}

if ($script:Failures.Count -gt 0) {
    foreach ($f in $script:Failures) {
        Write-Output ("FAIL {0}:{1} — {2}" -f $f.File, $f.Line, $f.Message)
    }
    Write-Output ("RESULT FAIL {0} 项 / 检查 {1} 页、{2} 条相对链接" -f $script:Failures.Count, $script:CheckedPages, $script:CheckedLinks)
    exit 1
}

Write-Output ("PASS docs: {0} 页手写文档、{1} 条相对链接、0 失败" -f $script:CheckedPages, $script:CheckedLinks)
exit 0
